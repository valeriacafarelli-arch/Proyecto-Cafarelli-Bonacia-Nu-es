    private void jButton8ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton8ActionPerformed
        // TODO add your handling code here:
        try{
            String i = this.id.getText();
            String n = this.name.getText();
            String l = this.linea.getText();
            String z = this.zona.getText();
            String c = this.pas.getText();
            
            Estacion nueva = new Estacion(i,n,l,z,Integer.parseInt(c));
            grafo.agregarEstacion(nueva);
            tabla.insertar(i, grafo.buscarVertice(i));
            
            
            
                        
        }catch(Exception e){
            
        }
    }//GEN-LAST:event_jButton8ActionPerformed

