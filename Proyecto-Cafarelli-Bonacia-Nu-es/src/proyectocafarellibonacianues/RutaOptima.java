    public void actualizarDropdowns() {
        idA.removeAllItems();
        idB.removeAllItems();

        if (grafo != null && grafo.getCabeza() != null) {
            Vertice aux = grafo.getCabeza();
            while (aux != null) {
                String item = aux.estacion.id_estacion + " - " + aux.estacion.nombre;
                idA.addItem(item);
                idB.addItem(item);
                aux = aux.siguiente;
            }
        }
    }
