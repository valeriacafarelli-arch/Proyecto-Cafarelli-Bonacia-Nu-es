    public Component obtenerPanelGrafo(Grafoo grafoPropio) {
        System.setProperty("org.graphstream.ui", "swing");

        Graph graph = new SingleGraph("Red de Estaciones");

        String estiloCSS
                = "node { "
                + "   fill-color: #E74C3C; "
                + "   size: 15px; "
                + "   text-alignment: under; "
                + "   text-color: #333; "
                + "   text-style: bold; "
                + "   text-background-mode: plain; "
                + "   text-background-color: white; "
                + "} "
                + "edge { "
                + "   fill-color: #95A5A6; "
                + "   size: 2px; "
                + "   text-color: #2980B9; "
                + "   text-size: 12px; "
                + "}";

        graph.setAttribute("ui.stylesheet", estiloCSS);
        graph.setAttribute("ui.antialias");
        graph.setAttribute("ui.quality");

        if (grafoPropio != null && grafoPropio.getCabeza() != null) {
            Vertice aux = grafoPropio.getCabeza();
            while (aux != null) {
                Node n = graph.addNode(aux.estacion.id_estacion);
                n.setAttribute("ui.label", aux.estacion.nombre);
                aux = aux.siguiente;
            }

            aux = grafoPropio.getCabeza();
            while (aux != null) {
                for (int i = 0; i < aux.adyacentes.getTamano(); i++) {
                    Conexion con = (Conexion) aux.adyacentes.obtener(i);
                    String idOrigen = con.Estacion_Origen.estacion.id_estacion;
                    String idDestino = con.Estacion_Destino.estacion.id_estacion;

                    String idArista = (idOrigen.compareTo(idDestino) < 0)
                            ? idOrigen + "-" + idDestino
                            : idDestino + "-" + idOrigen;

                    if (graph.getEdge(idArista) == null) {
                        Edge e = graph.addEdge(idArista, idOrigen, idDestino, false);
                        e.setAttribute("ui.label", con.Tiempo_Minutos + "m");
                    }
                }
                aux = aux.siguiente;
            }
        }

        Viewer viewer = new SwingViewer(graph, Viewer.ThreadingModel.GRAPH_IN_ANOTHER_THREAD);
        viewer.enableAutoLayout();

        ViewPanel viewPanel = (ViewPanel) viewer.addDefaultView(false);

        return viewPanel;
    }

